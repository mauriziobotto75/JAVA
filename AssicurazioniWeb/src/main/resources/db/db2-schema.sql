CREATE TABLE POLIZZE
(
    COD_POLIZZA     CHAR(10)     NOT NULL,
    NOME_CLIENTE    VARCHAR(40),
    INDIRIZZO       VARCHAR(60),
    IMPORTO         DECIMAL(9, 2),
    SCADENZA        DATE,
    SIGLA_AUTO      CHAR(10),
    NUM_CAVALLI     SMALLINT,
    STATO_PAGAMENTO CHAR(1),
    DATA_PAGAMENTO  DATE,
    CONSTRAINT PK_POLIZZE PRIMARY KEY (COD_POLIZZA),
    CONSTRAINT CK_POLIZZE_STATO_PAGAMENTO CHECK (STATO_PAGAMENTO IN ('N', 'P'))
);
